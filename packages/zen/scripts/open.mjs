/* The open faces a type system may pair beside Zen, shipped as bytes.
 *
 * Eighteen SIL OFL 1.1 families, each read from its own OFL.txt in
 * github.com/google/fonts. A page that sets a poster, a document or a deck in one
 * must not ask a third party's server for it, so the Latin subset of each is a file
 * here and a @font-face rule names it. A rule downloads nothing until a glyph uses
 * it, so a page may carry them all.
 *
 * Run: node scripts/open.mjs
 *   writes dist/open/<family>.woff2, dist/open/<family>.css (one family, urls beside it),
 *   dist/open.css (every family, urls under open/) and dist/open.{js,d.ts} (the list).
 *
 * The bytes are read from the font host once, here, and nowhere at runtime.
 */
import { mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const DIST = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist')
const OUT = join(DIST, 'open')
// A browser that takes woff2 is what makes the host answer with woff2.
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'

/** family, the axes query the host takes, and the OFL directory. */
export const FAMILIES = [
  ['Inter', 'Inter:ital,wght@0,400..800;1,400..800', 'inter', 'sans'],
  ['Manrope', 'Manrope:wght@400..800', 'manrope', 'sans'],
  ['DM Sans', 'DM+Sans:ital,wght@0,400..700;1,400..700', 'dmsans', 'sans'],
  ['Work Sans', 'Work+Sans:ital,wght@0,400..700;1,400..700', 'worksans', 'sans'],
  ['IBM Plex Sans', 'IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;0,700;1,400', 'ibmplexsans', 'sans'],
  ['Space Grotesk', 'Space+Grotesk:wght@400..700', 'spacegrotesk', 'display'],
  ['Archivo', 'Archivo:ital,wght@0,400..900;1,400..900', 'archivo', 'display'],
  ['Bricolage Grotesque', 'Bricolage+Grotesque:wght@400..800', 'bricolagegrotesque', 'display'],
  ['Syne', 'Syne:wght@400..800', 'syne', 'display'],
  ['Fraunces', 'Fraunces:ital,wght@0,400..900;1,400..900', 'fraunces', 'serif'],
  ['Playfair Display', 'Playfair+Display:ital,wght@0,400..900;1,400..900', 'playfairdisplay', 'serif'],
  ['DM Serif Display', 'DM+Serif+Display:ital@0;1', 'dmserifdisplay', 'serif'],
  ['Instrument Serif', 'Instrument+Serif:ital@0;1', 'instrumentserif', 'serif'],
  ['Cormorant Garamond', 'Cormorant+Garamond:ital,wght@0,400..700;1,400..700', 'cormorantgaramond', 'serif'],
  ['EB Garamond', 'EB+Garamond:ital,wght@0,400..800;1,400..800', 'ebgaramond', 'serif'],
  ['Source Serif 4', 'Source+Serif+4:ital,wght@0,400..700;1,400..700', 'sourceserif4', 'serif'],
  ['IBM Plex Mono', 'IBM+Plex+Mono:ital,wght@0,400;0,500;0,600;1,400', 'ibmplexmono', 'mono'],
  ['JetBrains Mono', 'JetBrains+Mono:ital,wght@0,400..700;1,400..700', 'jetbrainsmono', 'mono'],
]

const get = async (url) => {
  const r = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!r.ok) throw new Error(`${url} ${r.status}`)
  return r
}

rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

const all = []
const list = []
for (const [family, query, dir, role] of FAMILIES) {
  const css = await (await get(`https://fonts.googleapis.com/css2?family=${query}&display=swap`)).text()
  const slug = family.toLowerCase().replace(/[^a-z0-9]+/g, '-')
  const rules = []
  for (const [, subset, body] of css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g)) {
    if (subset !== 'latin') continue
    const style = /font-style: (\w+)/.exec(body)[1]
    const weight = /font-weight: ([\d ]+)/.exec(body)[1].trim()
    const range = /unicode-range: ([^;]+)/.exec(body)[1]
    const src = /url\((https:[^)]+)\)/.exec(body)?.[1]
    if (!src) throw new Error(`${family}: no url in ${body.slice(0, 200)}`)
    const file = `${slug}-${style}-${weight.replace(' ', '-')}.woff2`
    writeFileSync(join(OUT, file), Buffer.from(await (await get(src)).arrayBuffer()))
    rules.push({ style, weight, range, file })
  }
  if (!rules.length) throw new Error(`${family}: no latin faces`)
  const face = (r, base) =>
    `@font-face {\n  font-family: '${family}';\n  font-style: ${r.style};\n  font-weight: ${r.weight};\n  font-display: swap;\n  src: url(${base}${r.file}) format('woff2');\n  unicode-range: ${r.range};\n}\n`
  writeFileSync(join(OUT, `${slug}.css`), `/* ${family}, SIL OFL 1.1: https://github.com/google/fonts/blob/main/ofl/${dir}/OFL.txt */\n${rules.map((r) => face(r, './')).join('')}`)
  all.push(`/* ${family} */\n${rules.map((r) => face(r, './open/')).join('')}`)
  list.push({ family, slug, role, licence: `https://github.com/google/fonts/blob/main/ofl/${dir}/OFL.txt` })
}

writeFileSync(join(DIST, 'open.css'), `/* The open faces beside Zen, generated by scripts/open.mjs. Do not edit.\n *\n *   import '@hanzo/font/open.css'\n *\n * Latin subset, font-display: swap. A rule fetches nothing until a glyph uses it. */\n${all.join('\n')}`)
writeFileSync(join(DIST, 'open.js'), `/* The open faces, generated by scripts/open.mjs. Do not edit. */\nexport const OPEN = ${JSON.stringify(list, null, 2)}\n`)
writeFileSync(join(DIST, 'open.d.ts'), `export interface Open {\n  family: string\n  /** The file name under open/: <slug>.css names this family's faces, beside its woff2. */\n  slug: string\n  role: 'sans' | 'serif' | 'display' | 'mono'\n  /** Its OFL.txt. */\n  licence: string\n}\nexport declare const OPEN: readonly Open[]\n`)
console.log(`open: ${list.length} families, ${all.length} stylesheets`)
