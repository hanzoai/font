/* The open faces a type system may pair beside Zen, as bytes: the Latin subset of each SIL OFL 1.1
 * family, read once from the font host, so a page never asks a third party for one.
 *
 * Run: node scripts/open.ts
 *   writes dist/open/<slug>.woff2 and <slug>.css, dist/open.css (every family) and dist/open.{js,d.ts}. */
import { mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const DIST = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist')
const OUT = join(DIST, 'open')
// A browser that takes woff2 is what makes the host answer with woff2.
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'

/** The family, the axes its host takes, and its role. */
const FAMILIES: [family: string, axes: string, role: string][] = [
  ['Inter', 'ital,wght@0,400..800;1,400..800', 'sans'],
  ['Manrope', 'wght@400..800', 'sans'],
  ['DM Sans', 'ital,wght@0,400..700;1,400..700', 'sans'],
  ['Work Sans', 'ital,wght@0,400..700;1,400..700', 'sans'],
  ['IBM Plex Sans', 'ital,wght@0,400;0,500;0,600;0,700;1,400', 'sans'],
  ['Space Grotesk', 'wght@400..700', 'display'],
  ['Archivo', 'ital,wght@0,400..900;1,400..900', 'display'],
  ['Bricolage Grotesque', 'wght@400..800', 'display'],
  ['Syne', 'wght@400..800', 'display'],
  ['Fraunces', 'ital,wght@0,400..900;1,400..900', 'serif'],
  ['Playfair Display', 'ital,wght@0,400..900;1,400..900', 'serif'],
  ['DM Serif Display', 'ital@0;1', 'serif'],
  ['Instrument Serif', 'ital@0;1', 'serif'],
  ['Cormorant Garamond', 'ital,wght@0,400..700;1,400..700', 'serif'],
  ['EB Garamond', 'ital,wght@0,400..800;1,400..800', 'serif'],
  ['Source Serif 4', 'ital,wght@0,400..700;1,400..700', 'serif'],
  ['IBM Plex Mono', 'ital,wght@0,400;0,500;0,600;1,400', 'mono'],
  ['JetBrains Mono', 'ital,wght@0,400..700;1,400..700', 'mono'],
]

const get = async (url: string) => {
  const r = await fetch(url, { headers: { 'User-Agent': UA } })
  if (!r.ok) throw new Error(`${url} ${r.status}`)
  return r
}

rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

const all: string[] = []
const list: { family: string; slug: string; role: string; weights: number[]; italic: boolean; licence: string }[] = []
for (const [family, axes, role] of FAMILIES) {
  const css = await (await get(`https://fonts.googleapis.com/css2?family=${family.replace(/ /g, '+')}:${axes}&display=swap`)).text()
  const dir = family.toLowerCase().replace(/[^a-z0-9]/g, '')
  const slug = family.toLowerCase().replace(/[^a-z0-9]+/g, '-')
  const rules: { style: string; weight: string; range: string; file: string }[] = []
  for (const [, subset, body] of css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g)) {
    if (subset !== 'latin') continue
    const style = /font-style: (\w+)/.exec(body)![1]
    const weight = /font-weight: ([\d ]+)/.exec(body)![1].trim()
    const range = /unicode-range: ([^;]+)/.exec(body)![1]
    const src = /url\((https:[^)]+)\)/.exec(body)?.[1]
    if (!src) throw new Error(`${family}: no url in ${body.slice(0, 200)}`)
    const file = `${slug}-${style}-${weight.replace(' ', '-')}.woff2`
    writeFileSync(join(OUT, file), Buffer.from(await (await get(src)).arrayBuffer()))
    rules.push({ style, weight, range, file })
  }
  if (!rules.length) throw new Error(`${family}: no latin faces`)
  const face = (r: (typeof rules)[number], base: string) =>
    `@font-face {\n  font-family: '${family}';\n  font-style: ${r.style};\n  font-weight: ${r.weight};\n  font-display: swap;\n  src: url(${base}${r.file}) format('woff2');\n  unicode-range: ${r.range};\n}\n`
  writeFileSync(join(OUT, `${slug}.css`), `/* ${family}, SIL OFL 1.1: https://github.com/google/fonts/blob/main/ofl/${dir}/OFL.txt */\n${rules.map((r) => face(r, './')).join('')}`)
  all.push(`/* ${family} */\n${rules.map((r) => face(r, './open/')).join('')}`)
  const weights = [...new Set(rules.flatMap((r) => {
    const [lo, hi = lo] = r.weight.split(' ').map(Number)
    return Array.from({ length: (hi - lo) / 100 + 1 }, (_, i) => lo + i * 100)
  }))].sort((a, b) => a - b)
  list.push({ family, slug, role, weights, italic: rules.some((r) => r.style === 'italic'), licence: `https://github.com/google/fonts/blob/main/ofl/${dir}/OFL.txt` })
}

writeFileSync(join(DIST, 'open.css'), `/* The open faces beside Zen, generated by scripts/open.mjs. Do not edit.\n *\n *   import '@hanzo/font/open.css'\n *\n * Latin subset, font-display: swap. A rule fetches nothing until a glyph uses it. */\n${all.join('\n')}`)
writeFileSync(join(DIST, 'open.js'), `/* The open faces, generated by scripts/open.mjs. Do not edit. */\nexport const OPEN = ${JSON.stringify(list, null, 2)}\n`)
writeFileSync(join(DIST, 'open.d.ts'), `export interface Open {\n  family: string\n  /** The file name under open/: <slug>.css names this family's faces, beside its woff2. */\n  slug: string\n  role: 'sans' | 'serif' | 'display' | 'mono'\n  /** Every weight a face of it sets, in steps of 100. */\n  weights: readonly number[]\n  italic: boolean\n  /** Its OFL.txt. */\n  licence: string\n}\nexport declare const OPEN: readonly Open[]\n`)
console.log(`open: ${list.length} families, ${all.length} stylesheets`)
